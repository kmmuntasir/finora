// Generates src/styles/tokens.css from the design tokens in ../DESIGN.md.
// Dark tokens become :root variables; `light-*` tokens override them under
// [data-theme="light"]. Tailwind utilities map onto the variables via
// `@theme inline`, so both themes share one set of class names.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
const designPath = resolve(here, "../../DESIGN.md");
const outPath = resolve(here, "../src/styles/tokens.css");

const source = readFileSync(designPath, "utf8");
const match = /^---\n([\s\S]*?)\n---\n/.exec(source);
if (!match) throw new Error("DESIGN.md has no YAML front matter");
const tokens = parse(match[1]);

const TSHIRT = /^(?:\d?xs|sm|md|lg|\d?xl)$/;
const FONT_STACK = 'SolaimanLipi, system-ui, "Noto Sans Bengali", sans-serif';
const darkColors = Object.entries(tokens.colors).filter(([name]) => !name.startsWith("light-"));
const lightColors = Object.fromEntries(
  Object.entries(tokens.colors)
    .filter(([name]) => name.startsWith("light-"))
    .map(([name, value]) => [name.slice("light-".length), value]),
);

const lines = [
  "/* Generated by scripts/build-tokens.mjs from DESIGN.md. Do not edit. */",
  "",
  ":root {",
  "  color-scheme: dark;",
  ...darkColors.map(([name, value]) => `  --fin-${name}: ${value};`),
  "}",
  "",
  ':root[data-theme="light"] {',
  "  color-scheme: light;",
  ...Object.entries(lightColors).map(([name, value]) => `  --fin-${name}: ${value};`),
  "}",
  "",
  "@theme inline {",
  "  --color-*: initial;",
  "  --color-transparent: transparent;",
  "  --color-current: currentColor;",
  "  --color-white: #ffffff;",
  "  --color-black: #000000;",
  ...darkColors.map(([name]) => `  --color-${name}: var(--fin-${name});`),
  `  --font-sans: ${FONT_STACK};`,
  ...Object.entries(tokens.rounded).map(([name, value]) => `  --radius-${name}: ${value};`),
  // T-shirt spacing sizes match Tailwind's numeric 4px scale (sm = 2, md = 3, …)
  // and would shadow container sizes such as max-w-2xl, so only semantic
  // spacing tokens are exported.
  ...Object.entries(tokens.spacing)
    .filter(([name]) => !TSHIRT.test(name))
    .map(([name, value]) => `  --spacing-${name}: ${value};`),
  ...Object.entries(tokens.typography).flatMap(([name, t]) => [
    `  --text-${name}: ${t.fontSize};`,
    `  --text-${name}--line-height: ${t.lineHeight};`,
    `  --text-${name}--font-weight: ${t.fontWeight};`,
    ...(t.letterSpacing ? [`  --text-${name}--letter-spacing: ${t.letterSpacing};`] : []),
  ]),
  "}",
  "",
];

writeFileSync(outPath, lines.join("\n"));
console.log(`tokens: wrote ${outPath}`);
